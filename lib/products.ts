export function expiryLabel(days: number): { text: string; color: string; bg: string; border: string } {
  if (days === 0) return { text: 'Expires today', color: 'var(--urgency)', bg: 'rgba(255,107,53,0.12)', border: 'rgba(255,107,53,0.3)' }
  if (days === 1) return { text: '1 day left', color: 'var(--urgency)', bg: 'rgba(255,107,53,0.08)', border: 'rgba(255,107,53,0.2)' }
  return { text: `${days} days left`, color: 'var(--brand)', bg: 'rgba(200,241,53,0.08)', border: 'rgba(200,241,53,0.2)' }
}
